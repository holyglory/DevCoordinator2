-- Products and their explicitly adopted sources have persistent identities.
-- Existing repository/worktree identity and all historical authority remain intact.
CREATE TABLE projects (
 project_id TEXT PRIMARY KEY, name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 200),
 slug TEXT NOT NULL UNIQUE CHECK(length(slug) BETWEEN 1 AND 100), revision BIGINT NOT NULL DEFAULT 1 CHECK(revision>0),
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL, updated_by TEXT NOT NULL, refreshed_at TEXT
);
CREATE TABLE project_roots (
 project_id TEXT NOT NULL REFERENCES projects(project_id), root_id TEXT NOT NULL,
 kind TEXT NOT NULL CHECK(kind IN ('source','build')), label TEXT NOT NULL CHECK(length(label) BETWEEN 1 AND 200),
 absolute_path TEXT NOT NULL CHECK(length(absolute_path) BETWEEN 1 AND 4096),
 PRIMARY KEY(project_id,root_id), UNIQUE(project_id,absolute_path)
);
CREATE TABLE project_sources (
 project_id TEXT NOT NULL REFERENCES projects(project_id), repository_id TEXT NOT NULL REFERENCES repositories(repository_id),
 name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 200), github_url TEXT, default_branch TEXT,
 primary_checkout_id TEXT, refresh_state TEXT NOT NULL DEFAULT 'never', last_success TEXT, error TEXT,
 PRIMARY KEY(project_id,repository_id)
);
CREATE TABLE project_repository_memberships (
 project_id TEXT NOT NULL, repository_id TEXT NOT NULL, physical_repository_id TEXT NOT NULL REFERENCES repositories(repository_id),
 PRIMARY KEY(project_id,physical_repository_id),
 FOREIGN KEY(project_id,repository_id) REFERENCES project_sources(project_id,repository_id)
);
CREATE INDEX project_repository_memberships_source ON project_repository_memberships(project_id,repository_id,physical_repository_id);
CREATE INDEX project_repository_memberships_physical ON project_repository_memberships(physical_repository_id,project_id);
CREATE TABLE project_branches (
 project_id TEXT NOT NULL, branch_id TEXT NOT NULL, repository_id TEXT NOT NULL, branch_name TEXT NOT NULL CHECK(length(branch_name) BETWEEN 1 AND 512),
 head TEXT, remote_head TEXT, local_present BOOLEAN NOT NULL DEFAULT false, remote_present BOOLEAN,
 lifecycle TEXT NOT NULL DEFAULT 'unreviewed' CHECK(lifecycle IN ('unreviewed','planned','active','paused','blocked','ready','merged','abandoned','retired')),
 intent TEXT, outcome TEXT, owner TEXT, next_action TEXT, task_id TEXT,
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision>0), record_json JSONB NOT NULL,
 observed_at TEXT, updated_at TEXT NOT NULL, updated_by TEXT NOT NULL,
 PRIMARY KEY(project_id,branch_id), UNIQUE(project_id,repository_id,branch_name),
 FOREIGN KEY(project_id,repository_id) REFERENCES project_sources(project_id,repository_id)
);
CREATE INDEX project_branches_page ON project_branches(project_id,branch_id);
CREATE TABLE project_checkouts (
 project_id TEXT NOT NULL, worktree_id TEXT NOT NULL, repository_id TEXT NOT NULL, physical_repository_id TEXT NOT NULL REFERENCES repositories(repository_id),
 absolute_path TEXT NOT NULL CHECK(length(absolute_path) BETWEEN 1 AND 4096),
 role TEXT NOT NULL CHECK(role IN ('primary','worktree','deployment','scratch','clone')),
 protected_role TEXT CHECK(protected_role IN ('primary','deployment')),
 branch_id TEXT, branch_name TEXT, head TEXT, dirty BOOLEAN, exists_on_disk BOOLEAN,
 lifecycle TEXT NOT NULL DEFAULT 'active' CHECK(lifecycle IN ('planned','active','paused','blocked','ready','merged','abandoned','retired')),
 intent TEXT, outcome TEXT, owner TEXT, next_action TEXT, task_id TEXT,
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision>0), record_json JSONB NOT NULL,
 observed_at TEXT, updated_at TEXT NOT NULL, updated_by TEXT NOT NULL,
 PRIMARY KEY(project_id,worktree_id), UNIQUE(project_id,absolute_path),
 FOREIGN KEY(project_id,repository_id) REFERENCES project_sources(project_id,repository_id)
);
CREATE INDEX project_checkouts_page ON project_checkouts(project_id,worktree_id);
CREATE TABLE project_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id TEXT NOT NULL REFERENCES projects(project_id),
 repository_id TEXT, physical_repository_id TEXT, target_id TEXT, kind TEXT NOT NULL, summary TEXT NOT NULL,
 actor TEXT NOT NULL, at TEXT NOT NULL
);
CREATE INDEX project_events_page ON project_events(project_id,event_id DESC);
CREATE TABLE project_jobs (
 job_id TEXT PRIMARY KEY, project_id TEXT NOT NULL REFERENCES projects(project_id), kind TEXT NOT NULL,
 idempotency_key TEXT NOT NULL CHECK(length(idempotency_key) BETWEEN 1 AND 128),
 state TEXT NOT NULL CHECK(state IN ('queued','running','succeeded','failed','partial')),
 include_remote BOOLEAN NOT NULL DEFAULT true, authorized_repositories JSONB NOT NULL,
 cursor TEXT, queued_at TEXT NOT NULL, started_at TEXT, finished_at TEXT, error TEXT,
 actor TEXT NOT NULL, result_json JSONB, revision BIGINT NOT NULL DEFAULT 1, UNIQUE(project_id,kind,idempotency_key)
);
CREATE INDEX project_jobs_pending ON project_jobs(queued_at,job_id) WHERE state IN ('queued','running');
CREATE TABLE project_commits (
 project_id TEXT NOT NULL, branch_id TEXT NOT NULL, sha TEXT NOT NULL, position BIGINT NOT NULL,
 record_json JSONB NOT NULL, observed_at TEXT NOT NULL,
 PRIMARY KEY(project_id,branch_id,sha), UNIQUE(project_id,branch_id,position),
 FOREIGN KEY(project_id,branch_id) REFERENCES project_branches(project_id,branch_id)
);
-- Storage projection records distinct existing accounting identities; unknowns remain NULL.
CREATE TABLE project_storage (
 project_id TEXT NOT NULL, repository_id TEXT NOT NULL, physical_repository_id TEXT NOT NULL,
 accounting_id TEXT NOT NULL, artifact_id TEXT NOT NULL, worktree_id TEXT,
 kind TEXT NOT NULL CHECK(kind IN ('source','build','shared')), allocated_bytes BIGINT CHECK(allocated_bytes>=0),
 measured_at TEXT, PRIMARY KEY(project_id,accounting_id),
 FOREIGN KEY(project_id,repository_id) REFERENCES project_sources(project_id,repository_id)
);
CREATE TABLE project_branch_observations (
 project_id TEXT NOT NULL, branch_id TEXT NOT NULL, physical_repository_id TEXT NOT NULL REFERENCES repositories(repository_id),
 head TEXT, upstream TEXT, local_present BOOLEAN NOT NULL, observed_at TEXT NOT NULL,
 PRIMARY KEY(project_id,branch_id,physical_repository_id),
 FOREIGN KEY(project_id,branch_id) REFERENCES project_branches(project_id,branch_id)
);
CREATE INDEX project_branch_observations_visible ON project_branch_observations(project_id,physical_repository_id,branch_id);
CREATE TABLE project_remote_observations (
 job_id TEXT NOT NULL REFERENCES project_jobs(job_id), repository_id TEXT NOT NULL, branch_name TEXT NOT NULL,
 head TEXT NOT NULL, record_json JSONB NOT NULL, PRIMARY KEY(job_id,repository_id,branch_name)
);
CREATE TABLE project_commit_pages (
 project_id TEXT NOT NULL, branch_id TEXT NOT NULL, after_position BIGINT NOT NULL,
 head TEXT NOT NULL, end_position BIGINT NOT NULL, has_more BOOLEAN NOT NULL, remote_cursor TEXT, observed_at TEXT NOT NULL,
 PRIMARY KEY(project_id,branch_id,after_position),
 FOREIGN KEY(project_id,branch_id) REFERENCES project_branches(project_id,branch_id)
);
